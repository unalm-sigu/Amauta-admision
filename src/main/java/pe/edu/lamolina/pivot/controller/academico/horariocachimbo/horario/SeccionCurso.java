package pe.edu.lamolina.pivot.controller.academico.horariocachimbo.horario;

public class SeccionCurso {

    private String claveTeoria;
    private String clavePractica;
    private String grupoTeoria;
    private String grupoPractica;

    public SeccionCurso() {
    }

    public String getClaveTeoria() {
        return claveTeoria;
    }

    public void setClaveTeoria(String claveTeoria) {
        this.claveTeoria = claveTeoria;
    }

    public String getClavePractica() {
        return clavePractica;
    }

    public void setClavePractica(String clavePractica) {
        this.clavePractica = clavePractica;
    }

    public String getGrupoTeoria() {
        return grupoTeoria;
    }

    public void setGrupoTeoria(String grupoTeoria) {
        this.grupoTeoria = grupoTeoria;
    }

    public String getGrupoPractica() {
        return grupoPractica;
    }

    public void setGrupoPractica(String grupoPractica) {
        this.grupoPractica = grupoPractica;
    }

}
