package pe.edu.lamolina.amauta.controller.tramite.plantillaConstancia;

public class AlumnoConstancia {

    private String codigo;
    private String apellidosNombres;
    private String carrera;
    private String matriculado;
    private String cicloInicio;
    private String cicloFin;

    public String getCodigo() {
        return codigo;
    }

    public void setCodigo(String codigo) {
        this.codigo = codigo;
    }

    public String getApellidosNombres() {
        return apellidosNombres;
    }

    public void setApellidosNombres(String apellidosNombres) {
        this.apellidosNombres = apellidosNombres;
    }

    public String getCarrera() {
        return carrera;
    }

    public void setCarrera(String carrera) {
        this.carrera = carrera;
    }

    public String getMatriculado() {
        return matriculado;
    }

    public void setMatriculado(String matriculado) {
        this.matriculado = matriculado;
    }

    public String getCicloInicio() {
        return cicloInicio;
    }

    public void setCicloInicio(String cicloInicio) {
        this.cicloInicio = cicloInicio;
    }

    public String getCicloFin() {
        return cicloFin;
    }

    public void setCicloFin(String cicloFin) {
        this.cicloFin = cicloFin;
    }

}
