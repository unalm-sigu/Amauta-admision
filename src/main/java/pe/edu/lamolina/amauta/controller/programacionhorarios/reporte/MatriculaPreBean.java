package pe.edu.lamolina.amauta.controller.programacionhorarios.reporte;

public class MatriculaPreBean {

    private String facultad;
    private String programa;
    private String paterno;
    private String materno;
    private String nombres;
    private String correo;
    private String codigo;
    private String curso;
    private String dia;
    private String clave;
    private String hora_dictado;
    private Long vacantes;
    private Long matriculados;
    private String modo_dictado;

    public MatriculaPreBean() {
    }

    public String getFacultad() {
        return facultad;
    }

    public void setFacultad(String facultad) {
        this.facultad = facultad;
    }

    public String getPrograma() {
        return programa;
    }

    public void setPrograma(String programa) {
        this.programa = programa;
    }

    public String getPaterno() {
        return paterno;
    }

    public void setPaterno(String paterno) {
        this.paterno = paterno;
    }

    public String getMaterno() {
        return materno;
    }

    public void setMaterno(String materno) {
        this.materno = materno;
    }

    public String getNombres() {
        return nombres;
    }

    public void setNombres(String nombres) {
        this.nombres = nombres;
    }

    public String getCorreo() {
        return correo;
    }

    public void setCorreo(String correo) {
        this.correo = correo;
    }

    public String getCodigo() {
        return codigo;
    }

    public void setCodigo(String codigo) {
        this.codigo = codigo;
    }

    public String getCurso() {
        return curso;
    }

    public void setCurso(String curso) {
        this.curso = curso;
    }

    public String getClave() {
        return clave;
    }

    public void setClave(String clave) {
        this.clave = clave;
    }

    public String getHora_dictado() {
        return hora_dictado;
    }

    public void setHora_dictado(String hora_dictado) {
        this.hora_dictado = hora_dictado;
    }

    public Long getVacantes() {
        return vacantes;
    }

    public void setVacantes(Long vacantes) {
        this.vacantes = vacantes;
    }

    public Long getMatriculados() {
        return matriculados;
    }

    public void setMatriculados(Long matriculados) {
        this.matriculados = matriculados;
    }

    public String getModo_dictado() {
        return modo_dictado;
    }

    public void setModo_dictado(String modo_dictado) {
        this.modo_dictado = modo_dictado;
    }

    public String getDia() {
        return dia;
    }

    public void setDia(String dia) {
        this.dia = dia;
    }

    

}
